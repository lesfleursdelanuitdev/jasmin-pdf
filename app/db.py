"""Persistence: SQLite (a single file in the data directory) or Postgres.

SQLite is the default. Setting ``DATABASE_URL`` switches to Postgres; both
classes offer the same ``execute`` / ``one`` / ``all`` with ``?`` placeholders.
"""
from __future__ import annotations

import functools
import json
import sqlite3
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

SCHEMA = """
CREATE TABLE IF NOT EXISTS templates (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft',          -- draft | published
    pdf_file TEXT NOT NULL,                        -- content-addressed, never changes
    revision INTEGER NOT NULL DEFAULT 1,
    definition TEXT NOT NULL,                      -- JSON (pages, layers, elements, stacks)
    product_handles TEXT NOT NULL DEFAULT '[]',    -- Shopify product handles (JSON list)
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS uploads (
    id TEXT PRIMARY KEY,
    filename TEXT,
    path TEXT NOT NULL,
    preview_path TEXT NOT NULL,
    width INTEGER NOT NULL,
    height INTEGER NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS designs (
    id TEXT PRIMARY KEY,
    template_id TEXT NOT NULL,
    template_revision INTEGER NOT NULL,
    snapshot TEXT,                                 -- template definition frozen at approval
    "values" TEXT NOT NULL DEFAULT '{}',
    status TEXT NOT NULL DEFAULT 'draft',          -- draft | approved | ordered
    summary TEXT,
    warnings TEXT NOT NULL DEFAULT '[]',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    approved_at TEXT
);
CREATE TABLE IF NOT EXISTS orders (
    id TEXT PRIMARY KEY,                           -- Shopify order id
    name TEXT,                                     -- e.g. #1001
    email TEXT,
    customer TEXT,
    shop TEXT,
    source TEXT NOT NULL DEFAULT 'shopify',        -- shopify | demo
    status TEXT NOT NULL DEFAULT 'received',       -- received | in_production | shipped
    total TEXT,
    currency TEXT,
    shipping_address TEXT,
    created_at TEXT NOT NULL,
    raw TEXT
);
CREATE TABLE IF NOT EXISTS order_items (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    order_id TEXT NOT NULL,
    line_item_id TEXT NOT NULL,
    design_id TEXT,
    title TEXT,
    variant TEXT,
    quantity INTEGER NOT NULL DEFAULT 1,
    print_file TEXT,
    status TEXT NOT NULL DEFAULT 'pending',        -- pending | ready | error
    error TEXT,
    UNIQUE(order_id, line_item_id)
);
CREATE TABLE IF NOT EXISTS admins (
    email TEXT PRIMARY KEY,                        -- lower case; may sign in to the admin
    added_by TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL
);
"""


def now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


class Database:
    def __init__(self, path: Path):
        path.parent.mkdir(parents=True, exist_ok=True)
        self._conn = sqlite3.connect(str(path), check_same_thread=False)
        self._conn.row_factory = sqlite3.Row
        self._lock = threading.RLock()
        with self._lock:
            self._conn.execute("PRAGMA journal_mode=WAL")
            self._conn.execute("PRAGMA foreign_keys=ON")
            self._conn.executescript(SCHEMA)
            self._conn.commit()

    def execute(self, sql: str, params: tuple | dict = ()) -> sqlite3.Cursor:
        with self._lock:
            cur = self._conn.execute(sql, params)
            self._conn.commit()
            return cur

    def one(self, sql: str, params: tuple | dict = ()) -> dict[str, Any] | None:
        with self._lock:
            row = self._conn.execute(sql, params).fetchone()
        return dict(row) if row else None

    def all(self, sql: str, params: tuple | dict = ()) -> list[dict[str, Any]]:
        with self._lock:
            rows = self._conn.execute(sql, params).fetchall()
        return [dict(r) for r in rows]

    def template_for_handle(self, handle: str, exclude: str | None = None, published: bool = False) -> dict[str, Any] | None:
        """A template whose product handles (a JSON list) include ``handle``."""
        sql = "SELECT templates.* FROM templates, json_each(templates.product_handles) j WHERE j.value=?"
        params: list[Any] = [handle]
        if exclude is not None:
            sql += " AND templates.id<>?"
            params.append(exclude)
        if published:
            sql += " AND templates.status='published'"
        return self.one(sql, tuple(params))

    def close(self) -> None:
        with self._lock:
            self._conn.close()


# Postgres ----------------------------------------------------------------------
# Same tables and column types as SQLite: JSON and timestamps stay TEXT. The
# item id is an identity column that accepts explicit values, so rows copied
# from SQLite keep their ids.
PG_SCHEMA = SCHEMA.replace(
    "id INTEGER PRIMARY KEY AUTOINCREMENT", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
)


@functools.lru_cache(maxsize=512)
def to_pg(sql: str) -> str:
    """Rewrite ``?`` placeholders as ``%s`` and escape literal ``%``, leaving quoted text alone."""
    out: list[str] = []
    quote = ""
    for ch in sql:
        if quote:
            if ch == quote:
                quote = ""
        elif ch in "'\"":
            quote = ch
        elif ch == "?":
            out.append("%s")
            continue
        if ch == "%":
            out.append("%")
        out.append(ch)
    return "".join(out)


def _statements(script: str) -> list[str]:
    lines = [line.split("--", 1)[0] for line in script.splitlines()]
    return [stmt.strip() for stmt in "\n".join(lines).split(";") if stmt.strip()]


# Only this app, connecting as the tables' owner, may touch the tables. A hosted
# Postgres such as Supabase also serves the public schema over a web API to the
# roles "anon" and "authenticated", using a key that is public by design: row
# level security with no policy shuts that door (the owner is not subject to it),
# and the roles lose their table privileges as well.
PG_TABLES = ("templates", "uploads", "designs", "orders", "order_items", "admins")
PG_LOCKDOWN = [f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY" for t in PG_TABLES] + [
    """
    DO $$
    DECLARE r text;
    BEGIN
      FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
          EXECUTE format('REVOKE ALL ON TABLE templates, uploads, designs, orders, order_items, admins FROM %I', r);
          EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM %I', r);
        END IF;
      END LOOP;
    END $$
    """
]


class PostgresDatabase:
    """Postgres through a small connection pool.

    ``url`` may be a pooled (PgBouncer, transaction mode) address, so statements
    are never prepared and every statement commits on its own. The schema is
    created over ``schema_url`` (a direct connection) when one is given.
    """

    def __init__(self, url: str, schema_url: str = ""):
        import psycopg
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        with psycopg.connect(schema_url or url, autocommit=True, prepare_threshold=None) as conn:
            for stmt in _statements(PG_SCHEMA):
                conn.execute(stmt)
            for stmt in PG_LOCKDOWN:
                conn.execute(stmt)
        # One connection stays open, so a request does not pay for a new one. It is
        # not tested before each use (that would double every query's round trip
        # to a database far away); a statement that finds it dead is run once more
        # on a fresh connection instead.
        self._broken = psycopg.OperationalError
        self._pool = ConnectionPool(
            url,
            min_size=1,
            max_size=10,
            max_idle=300,
            kwargs={"autocommit": True, "prepare_threshold": None, "row_factory": dict_row},
            open=True,
        )

    def _run(self, sql: str, params: tuple | dict, fetch: str = ""):
        sql = to_pg(sql)
        for attempt in (1, 2):
            try:
                with self._pool.connection() as conn:
                    cur = conn.execute(sql, params)
                    return cur.fetchone() if fetch == "one" else cur.fetchall() if fetch == "all" else None
            except self._broken:
                if attempt == 2:
                    raise

    def execute(self, sql: str, params: tuple | dict = ()) -> None:
        self._run(sql, params)

    def one(self, sql: str, params: tuple | dict = ()) -> dict[str, Any] | None:
        return self._run(sql, params, "one")

    def all(self, sql: str, params: tuple | dict = ()) -> list[dict[str, Any]]:
        return self._run(sql, params, "all")

    def template_for_handle(self, handle: str, exclude: str | None = None, published: bool = False) -> dict[str, Any] | None:
        """A template whose product handles (a JSON list) include ``handle``."""
        sql = "SELECT * FROM templates WHERE product_handles::jsonb @> jsonb_build_array(?::text)"
        params: list[Any] = [handle]
        if exclude is not None:
            sql += " AND id<>?"
            params.append(exclude)
        if published:
            sql += " AND status='published'"
        return self.one(sql + " ORDER BY id LIMIT 1", tuple(params))

    def close(self) -> None:
        self._pool.close()


def open_database(path: Path, url: str = "", schema_url: str = "") -> Database | PostgresDatabase:
    """Postgres when a database URL is configured, otherwise the SQLite file at ``path``."""
    return PostgresDatabase(url, schema_url) if url else Database(path)


def loads(value: str | None, default: Any = None) -> Any:
    if value is None or value == "":
        return default
    return json.loads(value)


def dumps(value: Any) -> str:
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)
